        CHECK (status IN ('PRESENT', 'LATE', 'ABSENT')),
    CONSTRAINT ck_record_source
        CHECK (source IN ('NFC', 'AUTO_ABSENCE', 'MANUAL')),
    CONSTRAINT ck_record_source_status
        CHECK (
            (source = 'NFC' AND status IN ('PRESENT', 'LATE'))
            OR (source = 'AUTO_ABSENCE' AND status = 'ABSENT')
            OR source = 'MANUAL'
        ),
    CONSTRAINT ck_record_manual_actor
        CHECK (
            (source = 'MANUAL'
                AND (created_by_account_id IS NOT NULL
                    OR updated_by_account_id IS NOT NULL))
            OR
            (source <> 'MANUAL'
                AND created_by_account_id IS NULL)
        ),
    CONSTRAINT ck_record_band_snapshot
        CHECK (
            (status IN ('PRESENT', 'LATE')
                AND attendance_band_id IS NOT NULL
                AND band_sequence_snapshot IS NOT NULL
                AND band_sequence_snapshot > 0
                AND band_label_snapshot IS NOT NULL
                AND char_length(btrim(band_label_snapshot)) > 0
                AND checked_in_at IS NOT NULL)
            OR
            (status = 'ABSENT'
                AND attendance_band_id IS NULL
                AND band_sequence_snapshot IS NULL
                AND band_label_snapshot IS NULL
                AND checked_in_at IS NULL)
        )
);

