    CONSTRAINT ck_band_sequence
        CHECK (sequence_no > 0),
    CONSTRAINT ck_band_label
        CHECK (char_length(btrim(label)) > 0),
    CONSTRAINT ck_band_parent_status
        CHECK (parent_status IN ('PRESENT', 'LATE'))
);


CREATE TABLE public.attendance_day (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL,
    attendance_date DATE NOT NULL,
    policy_version_id BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'SCHEDULED',
    created_by_account_id BIGINT NOT NULL,
    canceled_by_account_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finalized_at TIMESTAMPTZ,
    canceled_at TIMESTAMPTZ,
    cancel_reason TEXT,
    CONSTRAINT uq_attendance_day_department_date
        UNIQUE (department_id, attendance_date),
    CONSTRAINT uq_attendance_day_scope
        UNIQUE (id, department_id),
    CONSTRAINT uq_attendance_day_policy_scope
        UNIQUE (id, policy_version_id),
    CONSTRAINT fk_attendance_day_department
        FOREIGN KEY (department_id)
        REFERENCES public.department (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_attendance_day_policy
        FOREIGN KEY (policy_version_id, department_id)
        REFERENCES public.attendance_policy_version (id, department_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_attendance_day_created_by
        FOREIGN KEY (created_by_account_id)
        REFERENCES public.account (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_attendance_day_canceled_by
        FOREIGN KEY (canceled_by_account_id)
        REFERENCES public.account (id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_attendance_day_status
        CHECK (status IN ('SCHEDULED', 'FINALIZED', 'CANCELED')),
    CONSTRAINT ck_attendance_day_state_fields
        CHECK (
            (status = 'SCHEDULED'
                AND finalized_at IS NULL
                AND canceled_at IS NULL
                AND canceled_by_account_id IS NULL
                AND cancel_reason IS NULL)
            OR
            (status = 'FINALIZED'
                AND finalized_at IS NOT NULL
                AND canceled_at IS NULL
                AND canceled_by_account_id IS NULL
                AND cancel_reason IS NULL)
            OR
            (status = 'CANCELED'
                AND finalized_at IS NULL
                AND canceled_at IS NOT NULL
                AND canceled_by_account_id IS NOT NULL
                AND cancel_reason IS NOT NULL
                AND char_length(btrim(cancel_reason)) > 0)
        )
);

CREATE INDEX idx_attendance_day_unfinalized
    ON public.attendance_day (attendance_date, id)
    WHERE status = 'SCHEDULED';

CREATE INDEX idx_attendance_day_policy_date
    ON public.attendance_day (policy_version_id, attendance_date DESC);

CREATE INDEX idx_attendance_day_created_by
    ON public.attendance_day (created_by_account_id);

CREATE INDEX idx_attendance_day_canceled_by
    ON public.attendance_day (canceled_by_account_id)
    WHERE canceled_by_account_id IS NOT NULL;


