-- The following multi-row and cross-table rules must be validated in the
-- application transaction or implemented later as dedicated PostgreSQL
-- triggers/functions:
--
-- 1. A published policy and its attendance_band rows are immutable.
-- 2. Policy publication requires:
--      - sequence numbers starting at 1 with no gaps;
--      - exactly one PRESENT band at sequence 1;
--      - one or more LATE bands after sequence 1;
--      - check_in_start_time <= the first upper_time;
--      - upper_time values strictly increasing by sequence.
-- 3. attendance_day may reference only a PUBLISHED policy.
-- 4. Normal attendance_target changes are allowed only before check-in starts.
--    The omitted-target recovery exception must atomically insert an active
--    MANUAL target and a MANUAL attendance_record with an authenticated actor
--    and nonblank reason; it is forbidden for CANCELED days.
-- 5. attendance_record may be created only when attendance_target.is_target is
--    true.
-- 6. An attendance_day with attendance_record rows cannot become CANCELED.
-- 7. Card status and active nfc_card_assignment must be updated atomically.
-- 8. Shared rows use this order when applicable: department, device,
--    request-specific tag event (check-in only), affected attendance_day rows
--    in ascending id order, membership/card, target/record, then log. The
--    parent rows must be locked before inserting tag_event_log because its FKs
--    take implicit parent locks. New attendance-day snapshots and roster
--    changes both lock the department row first. This includes check-in,
--    target or policy changes, card or membership changes, cancel, manual
--    correction, and automatic absence finalization. Check-in must re-read and
--    lock card and membership state after obtaining the day lock.
-- 9. An administrator update to attendance status, checked-in time, or band
--     must set attendance_record.source to MANUAL and updated_by_account_id in
--     the same statement. A note-only update preserves the existing source.

