-- Attend MVP target schema for a fresh database.
-- Target: PostgreSQL 15+
-- Legacy databases adopt and extend the existing member table through the
-- guarded Flyway path in MIGRATION_PLAN.md. This reference DDL does not drop
-- or migrate authentications/attendance/attendance_log.

BEGIN;

CREATE TABLE public.department (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_department_name
        CHECK (char_length(btrim(name)) > 0)
);

CREATE UNIQUE INDEX uq_department_name_ci
    ON public.department (lower(btrim(name)));


CREATE TABLE public.account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    password_hash TEXT,
    system_role TEXT,
    status TEXT NOT NULL DEFAULT 'PENDING_SETUP',
    password_changed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_account_username
        CHECK (char_length(btrim(username)) > 0),
    CONSTRAINT ck_account_password_hash
        CHECK (password_hash IS NULL OR char_length(password_hash) > 0),
    CONSTRAINT ck_account_system_role
        CHECK (system_role IS NULL OR system_role = 'SYSTEM_ADMIN'),
    CONSTRAINT ck_account_setup_state
        CHECK (
            (status = 'PENDING_SETUP'
                AND password_hash IS NULL
                AND password_changed_at IS NULL)
            OR
            (status = 'ACTIVE'
                AND password_hash IS NOT NULL
                AND password_changed_at IS NOT NULL)
            OR
            (status = 'DISABLED'
                AND (
                    (password_hash IS NULL AND password_changed_at IS NULL)
                    OR
                    (password_hash IS NOT NULL AND password_changed_at IS NOT NULL)
                ))
        ),
    CONSTRAINT ck_account_status
        CHECK (status IN ('PENDING_SETUP', 'ACTIVE', 'DISABLED'))
);

CREATE UNIQUE INDEX uq_account_username_ci
    ON public.account (lower(btrim(username)));


CREATE TABLE public.account_credential_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    purpose TEXT NOT NULL,
    token_hash TEXT NOT NULL,
    issued_by_account_id BIGINT NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    CONSTRAINT uq_account_credential_token_hash
        UNIQUE (token_hash),
    CONSTRAINT fk_account_credential_token_account
        FOREIGN KEY (account_id)
        REFERENCES public.account (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_account_credential_token_issuer
        FOREIGN KEY (issued_by_account_id)
        REFERENCES public.account (id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_account_credential_token_purpose
        CHECK (purpose IN ('INVITATION', 'RESET')),
    CONSTRAINT ck_account_credential_token_hash
        CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_account_credential_token_expiry
        CHECK (
            expires_at > issued_at
            AND expires_at <= issued_at + INTERVAL '30 minutes'
        ),
    CONSTRAINT ck_account_credential_token_consumed
        CHECK (
            consumed_at IS NULL
            OR (consumed_at >= issued_at AND consumed_at <= expires_at)
        ),
    CONSTRAINT ck_account_credential_token_revoked
        CHECK (revoked_at IS NULL OR revoked_at >= issued_at),
    CONSTRAINT ck_account_credential_token_terminal
        CHECK (NOT (consumed_at IS NOT NULL AND revoked_at IS NOT NULL))
);

CREATE UNIQUE INDEX uq_account_credential_token_active
    ON public.account_credential_token (account_id, purpose)
    WHERE consumed_at IS NULL AND revoked_at IS NULL;

CREATE INDEX idx_account_credential_token_account
    ON public.account_credential_token (account_id);

CREATE INDEX idx_account_credential_token_issuer
    ON public.account_credential_token (issued_by_account_id);


CREATE TABLE public.account_department_role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    role TEXT NOT NULL,
    assigned_by_account_id BIGINT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at TIMESTAMPTZ,
    CONSTRAINT fk_dept_role_account
        FOREIGN KEY (account_id)
        REFERENCES public.account (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_dept_role_department
        FOREIGN KEY (department_id)
        REFERENCES public.department (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_dept_role_assigned_by
        FOREIGN KEY (assigned_by_account_id)
        REFERENCES public.account (id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_dept_role_value
        CHECK (role = 'DEPARTMENT_ADMIN'),
    CONSTRAINT ck_dept_role_period
        CHECK (revoked_at IS NULL OR revoked_at >= assigned_at)
);

CREATE UNIQUE INDEX uq_dept_role_active
    ON public.account_department_role (account_id, department_id, role)
    WHERE revoked_at IS NULL;

CREATE INDEX idx_dept_role_department_account
    ON public.account_department_role (department_id, account_id);

CREATE INDEX idx_dept_role_account
    ON public.account_department_role (account_id);

CREATE INDEX idx_dept_role_assigned_by
    ON public.account_department_role (assigned_by_account_id)
    WHERE assigned_by_account_id IS NOT NULL;


CREATE TABLE public.member (
    id BIGSERIAL PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    age INTEGER,
    phone VARCHAR(255),
    birth DATE,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    card_uid VARCHAR(20) UNIQUE,
    active BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_member_name
        CHECK (char_length(btrim(name)) > 0),
    CONSTRAINT ck_member_phone
        CHECK (phone IS NULL OR char_length(btrim(phone)) > 0)
);

COMMENT ON COLUMN public.member.age IS
    'Legacy column; not used by the new attendance domain.';
COMMENT ON COLUMN public.member.birth IS
    'Legacy column; not used by the new attendance domain.';
COMMENT ON COLUMN public.member.created_at IS
    'Legacy timestamp without time zone; not used for attendance decisions or statistics.';
COMMENT ON COLUMN public.member.card_uid IS
    'Legacy migration evidence only; nfc_card and nfc_card_assignment are the operational source of truth.';


CREATE TABLE public.department_membership (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL,
    member_id BIGINT NOT NULL,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at TIMESTAMPTZ,
    created_by_account_id BIGINT,
    ended_by_account_id BIGINT,
    end_reason TEXT,
    CONSTRAINT uq_membership_scope
        UNIQUE (id, department_id, member_id),
    CONSTRAINT fk_membership_department
        FOREIGN KEY (department_id)
        REFERENCES public.department (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_membership_member
        FOREIGN KEY (member_id)
        REFERENCES public.member (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_membership_created_by
        FOREIGN KEY (created_by_account_id)
        REFERENCES public.account (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_membership_ended_by
        FOREIGN KEY (ended_by_account_id)
        REFERENCES public.account (id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_membership_period
        CHECK (ended_at IS NULL OR ended_at >= joined_at),
    CONSTRAINT ck_membership_end_state
        CHECK (
            (ended_at IS NULL
                AND ended_by_account_id IS NULL
                AND end_reason IS NULL)
            OR
            (ended_at IS NOT NULL
                AND ended_by_account_id IS NOT NULL
                AND end_reason IS NOT NULL
                AND char_length(btrim(end_reason)) > 0)
        )
);

CREATE UNIQUE INDEX uq_membership_one_active_per_member
    ON public.department_membership (member_id)
    WHERE ended_at IS NULL;

CREATE UNIQUE INDEX uq_membership_active_in_department
    ON public.department_membership (department_id, member_id)
    WHERE ended_at IS NULL;

CREATE INDEX idx_membership_department_member
    ON public.department_membership (department_id, member_id);

CREATE INDEX idx_membership_member_joined
    ON public.department_membership (member_id, joined_at DESC);

CREATE INDEX idx_membership_created_by
    ON public.department_membership (created_by_account_id)
    WHERE created_by_account_id IS NOT NULL;

CREATE INDEX idx_membership_ended_by
    ON public.department_membership (ended_by_account_id)
    WHERE ended_by_account_id IS NOT NULL;


CREATE TABLE public.nfc_card (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'AVAILABLE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_nfc_card_uid
        UNIQUE (uid),
    CONSTRAINT uq_nfc_card_identity
        UNIQUE (id, uid),
    CONSTRAINT ck_nfc_card_uid
        CHECK (
            uid ~ '^[0-9A-F]+$'
            AND char_length(uid) BETWEEN 8 AND 32
            AND mod(char_length(uid), 2) = 0
        ),
    CONSTRAINT ck_nfc_card_status
        CHECK (status IN ('AVAILABLE', 'ACTIVE', 'LOST', 'RETIRED'))
);


CREATE TABLE public.nfc_card_assignment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nfc_card_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    membership_id BIGINT NOT NULL,
    member_id BIGINT NOT NULL,
    assigned_by_account_id BIGINT,
    unassigned_by_account_id BIGINT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    unassigned_at TIMESTAMPTZ,
    end_reason TEXT,
    CONSTRAINT fk_card_assignment_card
        FOREIGN KEY (nfc_card_id)
        REFERENCES public.nfc_card (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_card_assignment_membership
        FOREIGN KEY (membership_id, department_id, member_id)
        REFERENCES public.department_membership (id, department_id, member_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_card_assignment_member
        FOREIGN KEY (member_id)
        REFERENCES public.member (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_card_assignment_assigned_by
        FOREIGN KEY (assigned_by_account_id)
        REFERENCES public.account (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_card_assignment_unassigned_by
        FOREIGN KEY (unassigned_by_account_id)
        REFERENCES public.account (id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_card_assignment_period
        CHECK (unassigned_at IS NULL OR unassigned_at >= assigned_at),
    CONSTRAINT ck_card_assignment_end_state
        CHECK (
            (unassigned_at IS NULL
                AND unassigned_by_account_id IS NULL
                AND end_reason IS NULL)
            OR
            (unassigned_at IS NOT NULL
                AND unassigned_by_account_id IS NOT NULL
                AND end_reason IS NOT NULL
                AND char_length(btrim(end_reason)) > 0)
        )
);

CREATE UNIQUE INDEX uq_card_one_active_assignment
    ON public.nfc_card_assignment (nfc_card_id)
    WHERE unassigned_at IS NULL;

CREATE UNIQUE INDEX uq_member_one_active_card
    ON public.nfc_card_assignment (member_id)
    WHERE unassigned_at IS NULL;

CREATE INDEX idx_card_assignment_department_member
    ON public.nfc_card_assignment (department_id, member_id);

CREATE INDEX idx_card_assignment_card
    ON public.nfc_card_assignment (nfc_card_id);

CREATE INDEX idx_card_assignment_member
    ON public.nfc_card_assignment (member_id);

CREATE INDEX idx_card_assignment_membership
    ON public.nfc_card_assignment (membership_id);

CREATE INDEX idx_card_assignment_assigned_by
    ON public.nfc_card_assignment (assigned_by_account_id)
    WHERE assigned_by_account_id IS NOT NULL;

CREATE INDEX idx_card_assignment_unassigned_by
    ON public.nfc_card_assignment (unassigned_by_account_id)
    WHERE unassigned_by_account_id IS NOT NULL;


CREATE TABLE public.device (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL,
    device_code TEXT NOT NULL,
    name TEXT NOT NULL,
    credential_hash TEXT NOT NULL,
    credential_version INTEGER NOT NULL DEFAULT 1,
    status TEXT NOT NULL DEFAULT 'INACTIVE',
    credential_issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    credential_tested_version INTEGER,
    credential_tested_at TIMESTAMPTZ,
    last_seen_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_device_code
        UNIQUE (device_code),
    CONSTRAINT uq_device_scope
        UNIQUE (id, department_id),
    CONSTRAINT fk_device_department
        FOREIGN KEY (department_id)
        REFERENCES public.department (id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_device_code
        CHECK (
            device_code = btrim(device_code)
            AND char_length(device_code) BETWEEN 1 AND 100
        ),
    CONSTRAINT ck_device_name
        CHECK (char_length(btrim(name)) > 0),
    CONSTRAINT ck_device_credential_hash
        CHECK (char_length(credential_hash) > 0),
    CONSTRAINT ck_device_credential_version
        CHECK (credential_version > 0),
    CONSTRAINT ck_device_credential_test
        CHECK (
            (credential_tested_version IS NULL
                AND credential_tested_at IS NULL)
            OR
            (credential_tested_version IS NOT NULL
                AND credential_tested_version = credential_version
                AND credential_tested_at IS NOT NULL
                AND credential_tested_at >= credential_issued_at)
        ),
    CONSTRAINT ck_device_active_credential_test
        CHECK (
            status <> 'ACTIVE'
            OR
            (credential_tested_version IS NOT NULL
                AND credential_tested_version = credential_version
                AND credential_tested_at IS NOT NULL
                AND credential_tested_at >= credential_issued_at)
        ),
    CONSTRAINT ck_device_status
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'REVOKED'))
);

CREATE INDEX idx_device_department_status
    ON public.device (department_id, status);


CREATE TABLE public.attendance_policy_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL,
    version_no INTEGER NOT NULL,
    name TEXT NOT NULL,
    check_in_start_time TIME WITHOUT TIME ZONE NOT NULL,
    status TEXT NOT NULL DEFAULT 'DRAFT',
    created_by_account_id BIGINT NOT NULL,
    published_by_account_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMPTZ,
    CONSTRAINT uq_policy_department_version
        UNIQUE (department_id, version_no),
    CONSTRAINT uq_policy_scope
        UNIQUE (id, department_id),
    CONSTRAINT fk_policy_department
        FOREIGN KEY (department_id)
        REFERENCES public.department (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_policy_created_by
        FOREIGN KEY (created_by_account_id)
